#!/usr/bin/env python3
"""Produce the offline MY33 near-surface table from CEDA's public OPeNDAP data."""

import argparse
import concurrent.futures
import hashlib
import json
import math
import re
import statistics
import time
import urllib.error
import urllib.request
from pathlib import Path

DIRECTORY = "/badc/mgs/data/macda/v2-0"
OPENDAP = "https://dap.ceda.ac.uk/thredds/dodsC" + DIRECTORY
# Habitat Base coordinates from lib/missions/mission_catalog.dart, east positive.
SITES = {
    "endeavour": (-2.295, 354.83),
    "gale": (-5.415, 137.725),
    "columbia-hills": (-14.5478, 175.6165),
    "valles-marineris": (-13.83, 300.845),
    "jezero": (18.386, 77.6564),
}
YEAR = 33
SEASON_STEP = 15
# This latitude strip contains the four adjacent grid cells of every site.
FIRST_LATITUDE = 13
LAST_LATITUDE = 21
QUERY = (
    "lon,lat,lev[0],time,Ls,MY_Ls,"
    f"temp.temp[0:1:359][0][{FIRST_LATITUDE}:1:{LAST_LATITUDE}][0:1:71]"
)


def download(url):
    for attempt in range(4):
        try:
            with urllib.request.urlopen(url, timeout=60) as response:
                return response.read().decode()
        except (OSError, urllib.error.HTTPError):
            if attempt == 3:
                raise
            time.sleep(2 ** attempt)


def read_file(name):
    result = download(f"{OPENDAP}/{name}.ascii?{QUERY}")
    blocks = result.split("---------------------------------------------\n", 1)[1]
    values, temperature = blocks.split("temp[", 1)
    dimensions = {}
    for block in values.strip().split("\n\n"):
        key, raw = block.split("\n", 1)
        dimensions[key.split("[")[0]] = list(map(float, raw.split(",")))
    assert abs(dimensions["lev"][0] - 0.9995) < 1e-6, name
    return name, dimensions, temperature.strip().splitlines()[1:]


def weights(latitude, longitude, latitudes, longitudes):
    east = (longitude + 180) % 360 - 180
    south = next(i for i, cell in enumerate(latitudes) if cell <= latitude)
    north = south - 1
    west = max(i for i, cell in enumerate(longitudes) if cell <= east)
    east_index = (west + 1) % len(longitudes)
    x = ((east - longitudes[west]) % 360) / (
        (longitudes[east_index] - longitudes[west]) % 360
    )
    y = (latitudes[north] - latitude) / (latitudes[north] - latitudes[south])
    return [
        (row - FIRST_LATITUDE, col, wy * wx)
        for row, wy in [(north, 1 - y), (south, y)]
        for col, wx in [(west, 1 - x), (east_index, x)]
    ]


def extract(file, bins):
    name, dims, records = file
    sites = {
        site: weights(*location, dims["lat"], dims["lon"])
        for site, location in SITES.items()
    }
    rows = LAST_LATITUDE - FIRST_LATITUDE + 1
    assert len(records) == rows * 360, name
    assert len(dims["time"]) == len(dims["Ls"]) == len(dims["MY_Ls"]) == 360
    for index, (sol, ls, year) in enumerate(zip(dims["time"], dims["Ls"], dims["MY_Ls"])):
        if year != YEAR:
            continue
        season = math.floor((ls + SEASON_STEP / 2) / SEASON_STEP) % (360 // SEASON_STEP)
        hour = round(sol * 12) % 12
        readings = [line.split(",") for line in records[index * rows:(index + 1) * rows]]
        for site, cells in sites.items():
            kelvin = 0.0
            for row, col, weight in cells:
                record = readings[row]
                assert record[0] == f"[{index}][0][{row}]", name
                sample = float(record[1 + col])
                assert 100 < sample < 400, (name, index, row, col)
                kelvin += sample * weight
            bins[site][season][hour].append(kelvin)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    listing = json.loads(download("https://data.ceda.ac.uk" + DIRECTORY + "?json"))
    names = sorted(
        item["name"]
        for item in listing["items"]
        if re.search(rf"MY{YEAR}SOY", item["name"])
    )
    assert len(names) == 23 and all(name.startswith("mro-mcs-reanalysis_") for name in names)
    bins = {
        site: [[[] for _ in range(12)] for _ in range(360 // SEASON_STEP)]
        for site in SITES
    }
    with concurrent.futures.ThreadPoolExecutor(max_workers=5) as pool:
        for file in pool.map(read_file, names):
            extract(file, bins)
            print(file[0], flush=True)

    output = [
        "// Generated by tool/generate_macda_climate.py. See docs/scientific_missions.md.",
        "// MACDA v2.0, doi:10.5285/cd037a9ea387438fabf4d674dbe53088 (OGL v3).",
        "// Rows are centered every 15° of Ls, columns every two hours of MTC.",
        "// Values are tenths of a kelvin at sigma = 0.9995.",
        "const macdaClimateData = <String, List<List<int>>>{",
    ]
    for site, seasons in bins.items():
        assert all(len(samples) >= 20 for row in seasons for samples in row), site
        assert 8016 <= sum(len(samples) for row in seasons for samples in row) <= 8028
        output.append(f"  '{site}': [")
        for row in seasons:
            output.append(f"    [{', '.join(str(round(statistics.fmean(s) * 10)) for s in row)}],")
        output.append("  ],")
    output.append("};")
    args.output.write_text("\n".join(output) + "\n")
    print(hashlib.sha256(args.output.read_bytes()).hexdigest())


if __name__ == "__main__":
    main()
